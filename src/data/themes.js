/** World key of a theme id ('forgeNight' -> 'forge'); sky themes and unknown ids -> 'sky'. */
export function themeWorld(id) {
  const m = /^(forge|frost|candy|citadel)/.exec(id || '');
  return m ? m[1] : 'sky';
}

